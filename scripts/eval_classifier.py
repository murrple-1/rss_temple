#!/usr/bin/env python
"""Score a trained artifact against the hand-labelled gold set.

Runs on the training box (no scikit-learn required -- this uses only the
pure-Python inference path in `api/text_classifier/classifier.py`, so it
runs fine in the project's regular venv). This is the only independent
measurement in the whole design: training labels are machine-generated by
`api/text_classifier/seed_labeler.py`, so "the model agrees with the seed
labeler" is not evidence of anything -- it would agree with itself. The gold
set is a few hundred entries labelled by a human, held out from training.

    python scripts/eval_classifier.py

Exit codes:
    0  both ship gates pass
    1  at least one ship gate fails (see the printed report)
    2  usage/IO error -- missing or malformed artifact, missing or empty
       gold set

Ship gates:
    Gate 1 -- the trained model's macro-F1 on the gold set must exceed the
              raw seed labeler's. If it doesn't, training added nothing:
              running the seed matcher directly would be simpler and more
              predictable than shipping a model.
    Gate 2 -- every label the model actually predicts at least once on the
              gold set must clear a per-label precision floor
              (`--precision-floor`, default 0.5). A label that is usually
              wrong is worse than one that is absent: it propagates into
              the feed and user tiers and would poison a recommender
              later. Only labels the model predicts are checked -- a label
              the model never fires needs no "excluding", it is already
              absent -- but a predicted label with no gold evidence at all
              scores precision 0.0 (see `prf` below) and so fails this
              gate rather than passing it silently: its precision cannot
              be verified from this gold set, and "unverified" must not
              read as "fine".
"""

import argparse
import json
import os
import sys
from collections import defaultdict
from typing import Any, TextIO

sys.path.insert(0, os.path.join(os.path.dirname(__file__), ".."))

from api.text_classifier.artifact import ArtifactError, load_artifact  # noqa: E402
from api.text_classifier.classifier import predict  # noqa: E402
from api.text_classifier.prep_content import prep_for_classification  # noqa: E402
from api.text_classifier.seed_labeler import label_text  # noqa: E402
from api.text_classifier.taxonomy import LABEL_NAMES, taxonomy_fingerprint  # noqa: E402


def prf(tp: int, fp: int, fn: int) -> tuple[float, float, float]:
    """Precision/recall/F1 from raw counts for one label.

    A label with zero predictions and zero gold truths (tp == fp == fn ==
    0) is expected and common with a small gold set -- eleven of the 23
    labels may never have received a single human vote. This returns
    0.0/0.0/0.0 for that case rather than raising ZeroDivisionError.

    That zero is not merely "avoid a crash". Whenever a label has zero
    gold truth, tp is always 0 (there is nothing to true-positive
    against), so precision is 0/(0 + fp): 0.0 whether the model fired
    false positives on it or stayed completely silent. Defining 0/0 as
    0.0 rather than skipping the label or treating it as automatically
    satisfied means that IF the model does predict such a label (see
    `run`'s `predicted_labels` filter, which is what actually decides
    Gate 2), it reads as failing the precision floor, not silently
    passing unchecked, because its precision genuinely cannot be
    verified from this gold set.
    """
    precision = tp / (tp + fp) if tp + fp else 0.0
    recall = tp / (tp + fn) if tp + fn else 0.0
    f1 = 2 * precision * recall / (precision + recall) if precision + recall else 0.0
    return precision, recall, f1


def score(
    predictions_by_uuid: dict[str, set[str] | frozenset[str]],
    gold_rows: list[dict[str, Any]],
) -> tuple[dict[str, tuple[float, float, float]], float, float]:
    """Per-label precision/recall/F1, the macro-F1 across all labels, and
    the fraction of gold rows for which `predictions_by_uuid` predicted at
    least one label ("coverage").

    Macro-F1 is the unweighted mean of `prf` over every name in
    `LABEL_NAMES`, including labels with zero gold truth in this gold set.
    That is deliberate: `score` is called identically for the model and
    for the raw seed labeler over the same gold set (see `run` below), so
    a zero-truth label contributes exactly the same value (0.0, per `prf`)
    to both macro averages. It therefore cannot bias which side wins
    Gate 1's comparison -- it only affects the two absolute macro-F1
    numbers, in the same direction, by the same amount.
    """
    tp: defaultdict[str, int] = defaultdict(int)
    fp: defaultdict[str, int] = defaultdict(int)
    fn: defaultdict[str, int] = defaultdict(int)
    covered = 0

    for row in gold_rows:
        predicted = predictions_by_uuid.get(row["uuid"], set())
        truth = set(row["labels"])
        if predicted:
            covered += 1
        for label in LABEL_NAMES:
            if label in predicted and label in truth:
                tp[label] += 1
            elif label in predicted:
                fp[label] += 1
            elif label in truth:
                fn[label] += 1

    per_label = {label: prf(tp[label], fp[label], fn[label]) for label in LABEL_NAMES}
    macro_f1 = sum(f for _, _, f in per_label.values()) / len(per_label)
    coverage = covered / len(gold_rows) if gold_rows else 0.0
    return per_label, macro_f1, coverage


def load_gold_rows(path: str) -> list[dict[str, Any]]:
    with open(path, "r") as f:
        return [json.loads(line) for line in f if line.strip()]


def build_predictions(
    artifact: Any, gold_rows: list[dict[str, Any]], max_labels: int
) -> tuple[dict[str, set[str]], dict[str, frozenset[str]]]:
    """Model and seed-labeler predictions for every gold row, keyed by uuid.

    Both sides score identically prepared text.
    `prep_for_classification` is the *only* truncation point in the whole
    pipeline (see its docstring in `api/text_classifier/prep_content.py`);
    feeding it raw `title`/`content_excerpt` untouched, exactly as
    `api/tasks/label_feed_entries.py` does in production, keeps this
    comparison honest -- concatenating the raw fields instead would let
    un-stripped HTML in `content_excerpt` change which n-grams form
    (e.g. an entity like "&nbsp;" tokenizing to a spurious "nbsp" word that
    breaks bigram adjacency) and silently diverge from what production
    actually scores.
    """
    model_predictions: dict[str, set[str]] = {}
    seed_predictions: dict[str, frozenset[str]] = {}
    for row in gold_rows:
        text = prep_for_classification(row["title"], row["content_excerpt"])
        model_predictions[row["uuid"]] = {
            p.label for p in predict(artifact, text, max_labels)
        }
        seed_predictions[row["uuid"]] = label_text(text)
    return model_predictions, seed_predictions


def run(
    args: argparse.Namespace, out: TextIO = sys.stdout, err: TextIO = sys.stderr
) -> int:
    """Score the artifact against the gold set and print the full report.

    Returns the intended process exit code rather than calling `sys.exit`
    directly, so callers (including tests) can inspect it without ending
    the process. `main` is the only caller that turns this into an actual
    exit.
    """
    try:
        artifact = load_artifact(args.artifact)
    except (OSError, ArtifactError) as e:
        print(f"error loading artifact at {args.artifact!r}: {e}", file=err)
        return 2

    if artifact.taxonomy_fingerprint != taxonomy_fingerprint():
        print(
            "warning: artifact's taxonomy_fingerprint does not match the "
            "current taxonomy -- seed terms have changed since this model "
            "was trained; scores below reflect the OLD taxonomy the model "
            "was fit against (see `manage.py checkclassifierlabels`)",
            file=err,
        )

    try:
        gold_rows = load_gold_rows(args.gold)
    except OSError as e:
        print(f"error reading gold set at {args.gold!r}: {e}", file=err)
        return 2

    if not gold_rows:
        print(f"error: gold set at {args.gold!r} has no rows", file=err)
        return 2

    model_predictions, seed_predictions = build_predictions(
        artifact, gold_rows, args.max_labels
    )

    model_per_label, model_macro, coverage = score(model_predictions, gold_rows)
    _, seed_macro, _ = score(seed_predictions, gold_rows)

    # Labels the model never predicted on any gold row are not subject to
    # the precision floor: there is nothing to exclude for a label that
    # already predicts nothing. Without this filter, every label absent
    # from a small gold set -- typically most of them -- would score the
    # 0/0 -> 0.0 convention from `prf` and get flagged as "BELOW PRECISION
    # FLOOR" regardless of whether the model ever fires it, which would
    # make Gate 2 fail on essentially any small gold set for reasons that
    # have nothing to do with the model being wrong about anything.
    predicted_labels: set[str] = (
        set().union(*model_predictions.values()) if model_predictions else set()
    )

    print(f"{'label':<32} {'prec':>6} {'rec':>6} {'f1':>6}", file=out)
    below_floor = []
    for label in LABEL_NAMES:
        precision, recall, f1 = model_per_label[label]
        flag = ""
        if label in predicted_labels and precision < args.precision_floor:
            below_floor.append(label)
            flag = "  <-- BELOW PRECISION FLOOR"
        print(
            f"{label:<32} {precision:>6.3f} {recall:>6.3f} {f1:>6.3f}{flag}", file=out
        )

    print(file=out)
    print(f"gold set:                {len(gold_rows)} row(s)", file=out)
    print(f"macro-F1 (model):        {model_macro:.3f}", file=out)
    print(f"macro-F1 (seed labeler): {seed_macro:.3f}", file=out)
    print(f"coverage:                {coverage:.3f}", file=out)
    print(file=out)

    gate1 = model_macro > seed_macro
    print(
        "GATE 1 model beats seed labeler on gold macro-F1: "
        f"{'PASS' if gate1 else 'FAIL'} "
        f"(model {model_macro:.3f} vs seed {seed_macro:.3f})",
        file=out,
    )
    if below_floor:
        print(
            f"GATE 2 precision floor ({args.precision_floor}): FAIL -- "
            f"{len(below_floor)} label(s) below floor: {', '.join(below_floor)}",
            file=out,
        )
        print(
            "  -> improve their seed terms and retrain, or exclude them "
            "from the shipped artifact",
            file=out,
        )
    else:
        print(f"GATE 2 precision floor ({args.precision_floor}): PASS", file=out)

    return 0 if gate1 and not below_floor else 1


def build_arg_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument(
        "--artifact",
        default="api/text_classifier/model/classifier.json",
        help="path to the trained artifact (default: %(default)s)",
    )
    parser.add_argument(
        "--gold",
        default="api/text_classifier/gold/gold_set.jsonl",
        help="path to the hand-labelled gold set JSONL (default: %(default)s)",
    )
    parser.add_argument(
        "--max-labels",
        type=int,
        default=3,
        help=(
            "top-N labels per entry, matching "
            "settings.CLASSIFIER_MAX_LABELS_PER_ENTRY (default: %(default)s)"
        ),
    )
    parser.add_argument(
        "--precision-floor",
        type=float,
        default=0.5,
        help="Gate 2 per-label precision floor (default: %(default)s)",
    )
    return parser


def main() -> None:
    args = build_arg_parser().parse_args()
    sys.exit(run(args))


if __name__ == "__main__":
    main()
